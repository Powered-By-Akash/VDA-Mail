from email.message import EmailMessage
from smtplib import SMTP_SSL
import smtplib


class SendVDAMail(SMTP_SSL):
    """
    SMTP SSL dispatcher with automatic provider selection (Outlook / Gmail).
    Establishes a secure connection, authenticates, dispatches the message, and disconnects.
    """
    def __init__(self, provider: str, sender_email: str, sender_email_pass: str, receiver_email: str, email_message):
        if str(provider).lower() == "outlook":
            server_name = "smtp-mail.outlook.com"
        else:
            server_name = "smtp.gmail.com"
        super().__init__(server_name)
        self.login(user=sender_email, password=sender_email_pass)
        self.sendmail(from_addr=sender_email, to_addrs=receiver_email, msg=email_message)
        self.quit()


class VDASecurityEmail(EmailMessage):
    """
    Transactional security verification email for OTPs, PINs, and security codes.
    """
    def __init__(self, user_email: str, name: str, security_pin_code: str, security_name: str, app_email: str,
                 security_type: str, firm_name: str, firm_email: str = ""):
        super().__init__()

        if str(security_type).lower() == "pin":
            type_name = "Security Pin"
        elif str(security_type).lower() == "code":
            type_name = "Security Code"
        else:
            type_name = security_type.title()

        message = (
            f"Hello {name},\n"
            f"This mail is auto generated by VDA for {security_name} {type_name}.\n"
            f"Your {security_name} {type_name} is {security_pin_code}.\n\n\n"
            f"Regards,\n{firm_name}\n\nSupport By Avik's Group"
        )

        self["From"] = app_email
        self["To"] = user_email
        self["Subject"] = f"{security_name} {type_name}"
        self.set_content(message)


