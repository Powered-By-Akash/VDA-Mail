class UDNUserSettingEmail(EmailMessage):
    """
    Security alert notification sent when a user profile or account setting is updated.
    """
    def __init__(self, user_email: str, udn_id: str, app_email: str, change_message_list: list):
        super().__init__()

        if len(change_message_list) == 1:
            change_message = change_message_list[0]
        elif len(change_message_list) == 2:
            change_message = f"{change_message_list[0]} and {change_message_list[1]}"
        else:
            change_message = f"{', '.join(change_message_list[:-1])} and {change_message_list[-1]}"

        message = (
            f"Hello {udn_id},\n"
            f"This mail is auto generated by PBA for changing user details.\n"
            f"You changed: {change_message}.\n\n\n"
            f"Regards,\nPowered By Akash\n\n"
            f"Note:-\n"
            f"- If you did not request changing details, email poweredbyakashteam@gmail.com for inquiry."
        )

        self["From"] = app_email
        self["To"] = user_email
        self["Subject"] = "Your Request Completed Successfully for Changed User Details"
        self.set_content(message)


