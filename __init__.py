class VDASecurityEmail(EmailMessage):
    def __init__(self, user_email:str, name:str, security_pin_code:str, security_name:str, app_email:str, security_type:str,
                 firm_name:str, firm_email:str):
        super().__init__()

        if security_type.lower() == "pin":
            type_name = "Security Pin"
        elif security_type.lower() == "code":
            type_name = "Security Code"
        message = (f"Hello {name},\nThis mail is auto generated by VDA for {security_name} {type_name}.\nYour {security_name} {type_name} is {security_pin_code}."
                   f"\n\n\nRegards,\n{firm_name}\n\nSupport By Avik's Group")

        self["From"] = app_email
        self["To"] = user_email
        self["Subject"] = f"{security_name} {type_name}"
        self.set_content(message)
