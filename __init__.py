class SendVDAMail(SMTP_SSL):
    def __init__(self, provider, sender_email, sender_email_pass, receiver_email, email_message):
        if provider == "outlook":
            server_name = "smtp-mail.outlook.com"
        else:
            server_name = "smtp.gmail.com"
        super().__init__(server_name)
        self.login(user=sender_email, password=sender_email_pass)
        self.sendmail(from_addr=sender_email, to_addrs=receiver_email, msg=email_message)
        self.quit()
